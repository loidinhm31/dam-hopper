impl std::fmt::Display for ManagedReadinessStatus {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Ready => write!(f, "ready"),
            Self::RestartRequired => write!(f, "restart-required"),
            Self::TrustRequired => write!(f, "trust-required"),
            Self::PolicyDisabled => write!(f, "policy-disabled"),
            Self::PathMismatch => write!(f, "path-mismatch"),
            Self::PermissionDenied => write!(f, "permission-denied"),
            Self::UnsupportedVersion => write!(f, "unsupported-version"),
            Self::Unverified => write!(f, "unverified"),
        }
    }
}

