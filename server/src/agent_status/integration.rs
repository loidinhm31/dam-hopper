#[derive(Debug, Error)]
pub enum IntegrationError {
    #[error("Agent directory must be an absolute path: '{0}'")]
    NonAbsolutePath(PathBuf),

    #[error("Agent directory does not exist or is not a directory: '{0}'")]
    InvalidAgentDirectory(PathBuf),

    #[error("Refusing to operate on symlink: '{0}'")]
    SymlinkNotAllowed(PathBuf),

    #[error("Target path is not a regular file: '{0}'")]
    NotRegularFile(PathBuf),

    #[error("Refusing to overwrite locally modified or unmanaged file at '{0}'")]
    RefusingOverwriteModified(PathBuf),

    #[error("Refusing to delete locally modified or unmanaged file at '{0}'")]
    RefusingDeleteModified(PathBuf),
    #[error("Configuration error: {0}")]
    ConfigurationError(String),

    #[error("Manifest corrupted at '{0}': {1}")]
    ManifestCorrupted(PathBuf, String),

    #[error("Conflict with local modifications or unmanaged entries: {0}")]
    Conflict(String),

    #[error("Agent restart required: {0}")]
    RestartRequired(String),

    #[error("I/O error: {0}")]
    Io(#[from] std::io::Error),
}

/// Installation status of the managed extension or hooks.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum ManagedInstallationStatus {
    Absent,
    Current,
    Outdated,
    Modified,
}

impl std::fmt::Display for ManagedInstallationStatus {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Absent => write!(f, "absent"),
            Self::Current => write!(f, "current"),
            Self::Outdated => write!(f, "outdated"),
            Self::Modified => write!(f, "modified"),
        }
    }
}

pub type ManagedExtensionStatus = ManagedInstallationStatus;

